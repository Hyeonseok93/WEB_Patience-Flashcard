def esc(s: str) -> str:
    return s.replace("'", "''")


def values_sql(pairs: list[tuple[str, str]]) -> str:
    lines = []
    for i, (front, back) in enumerate(pairs, 1):
        lines.append(f"        ('{esc(front)}', '{esc(back)}', {i})")
    return ",\n".join(lines)


def deck_block(name: str, pairs: list[tuple[str, str]]) -> str:
    return f"""INSERT INTO decks (name, owner_id, source_type)
VALUES ('{esc(name)}', NULL, 'BUILTIN');

INSERT INTO cards (deck_id, front_text, back_text, sort_order)
SELECT d.id, v.front, v.back, v.ord
FROM decks d
CROSS JOIN (
    VALUES
{values_sql(pairs)}
) AS v(front, back, ord)
WHERE d.name = '{esc(name)}' AND d.source_type = 'BUILTIN';
"""


